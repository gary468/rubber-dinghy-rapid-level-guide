"""Walkable-ground grids for zones whose mountains the straight-line route can't see (Mount Hyjal).

Reads the zone's map picture and marks each 1% cell walkable when most of it is the light valley
ground (green-to-red ratio >= 0.8); the brown mountain strokes and the tan parchment between them are
blocked. Islands under 40 cells (snow patches on peaks) are dropped. Writes TerrainData.lua.

Usage (the picture is Wowhead's Forever zone map; fetch it first, it isn't kept in the repo):
  curl -o <tmp>/616.jpg https://wow.zamimg.com/images/wow/classicplus/maps/enus/zoom/616.jpg
  python tools/terrain_mask.py TerrainData.lua 2482=<tmp>/616.jpg

Gary 17 Nov 2026, Mount Hyjal: "the mountains block the quests" - the Shrine of Aviana plateau and
the Tainted Foothills look a few steps apart on the map but there's no way down without Slow Fall.
"""
import sys
from PIL import Image

N, RATIO, SHARE, MIN_ISLAND = 100, 0.80, 0.5, 40


def grid(path):
    im = Image.open(path).convert("RGB")
    W, H = im.size
    px = im.load()
    g = []
    for j in range(N):
        row = []
        for i in range(N):
            x0, x1 = int(i / N * W), max(int((i + 1) / N * W), int(i / N * W) + 1)
            y0, y1 = int(j / N * H), max(int((j + 1) / N * H), int(j / N * H) + 1)
            tot = ok = 0
            for yy in range(y0, y1):
                for xx in range(x0, x1):
                    r, gg, _ = px[xx, yy]
                    tot += 1
                    ok += r > 90 and gg >= RATIO * r
            row.append(1 if ok / tot >= SHARE else 0)
        g.append(row)
    # drop small islands (8-connected)
    seen = [[False] * N for _ in range(N)]
    for j in range(N):
        for i in range(N):
            if g[j][i] and not seen[j][i]:
                part, st = [], [(i, j)]
                seen[j][i] = True
                while st:
                    a, b = st.pop()
                    part.append((a, b))
                    for da in (-1, 0, 1):
                        for db in (-1, 0, 1):
                            x, y = a + da, b + db
                            if 0 <= x < N and 0 <= y < N and g[y][x] and not seen[y][x]:
                                seen[y][x] = True
                                st.append((x, y))
                if len(part) < MIN_ISLAND:
                    for a, b in part: g[b][a] = 0
    return ["".join(str(c) for c in r) for r in g]


out = sys.argv[1]
lines = ["-- Generated by tools/terrain_mask.py - walkable ground per zone, 1% cells (row = y, column = x).",
         "-- '1' = valley floor, '0' = mountain. Read by Terrain.lua.",
         "local ADDON, ns = ...",
         "ns.terrainData = {"]
for arg in sys.argv[2:]:
    m, path = arg.split("=", 1)
    rows = grid(path)
    lines.append(f"  [{int(m)}] = {{ n = {N}, rows = {{")
    lines += [f'    "{r}",' for r in rows]
    lines.append("  } },")
lines.append("}")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", out)
