"""Builds Data_Loot.lua: what each dungeon boss drops (item IDs and drop chances only).

Usage:  python -I tools/gen_loot.py <ClassicDB_*.sql.gz> Data_Dungeons.lua Data_Loot.lua

Source: the CMaNGOS Classic database (https://github.com/cmangos/classic-db, GPLv3), its
creature_loot_template and reference_loot_template tables. Only facts are kept: which item a boss
drops and how often. Item names, icons, quality and stats are read from the game in play.
Kept: uncommon or better items and recipes; quest items are left out (the journal lists those from
QuestieDB) and so are loot lists shared by many creatures (random world drops).
Forever's new dungeons aren't in that database: their drops come from tools/forever_loot.json
(read from Wowhead's WoW Forever NPC pages; facts only).
"""
import gzip, json, os, re, sys
from collections import defaultdict

SQL, DUNGEONS, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
SHARED_REF = 5          # a reference list used by more creatures than this is a world-drop list
MIN_CHANCE = 0.5        # % - rarer than this isn't worth a line


def tuples(values):
    """Parse a MySQL VALUES list '(1,2,'a'),(3,...)' into Python tuples."""
    out, row, cur, i, n = [], [], [], 0, len(values)
    in_str = False
    while i < n:
        ch = values[i]
        if in_str:
            if ch == "\\" and i + 1 < n:
                cur.append(values[i + 1]); i += 2; continue
            if ch == "'":
                if i + 1 < n and values[i + 1] == "'":
                    cur.append("'"); i += 2; continue
                in_str = False; i += 1; continue
            cur.append(ch); i += 1; continue
        if ch == "'":
            in_str = True; cur.append("\x00"); i += 1; continue   # marks a string value
        if ch == "(":
            row, cur = [], []; i += 1; continue
        if ch == "," and row is not None:
            row.append("".join(cur)); cur = []; i += 1; continue
        if ch == ")":
            row.append("".join(cur)); out.append([v[1:] if v.startswith("\x00") else v for v in row])
            row, cur = None, []
            i += 1
            while i < n and values[i] in ",;\n ": i += 1
            continue
        cur.append(ch); i += 1
    return out


def read_tables(path, want):
    cols, rows = {}, defaultdict(list)
    current = None
    with gzip.open(path, "rt", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = re.match(r"CREATE TABLE `(\w+)`", line)
            if m:
                current = m.group(1) if m.group(1) in want else None
                if current: cols[current] = []
                continue
            if current and line.startswith("  `"):
                cols[current].append(re.match(r"  `(\w+)`", line).group(1))
                continue
            m = re.match(r"INSERT INTO `(\w+)` VALUES (.*)", line)
            if m and m.group(1) in want:
                rows[m.group(1)] += tuples(m.group(2))
    return cols, rows


def main():
    boss_npcs = sorted({int(x) for x in re.findall(r'\{"[^"]+",(\d+),\d+', open(DUNGEONS, encoding="utf-8").read()) if int(x) > 0})
    want = {"creature_template", "creature_loot_template", "reference_loot_template", "item_template"}
    cols, rows = read_tables(SQL, want)

    def idx(t, name):
        return cols[t].index(name)

    ct = cols["creature_template"]
    e_i, l_i = ct.index("Entry"), ct.index("LootId")
    loot_id = {int(r[e_i]): int(r[l_i]) for r in rows["creature_template"]}
    it = cols["item_template"]
    iq, ic = it.index("Quality"), it.index("class")
    item_info = {int(r[0]): (int(r[iq]), int(r[ic])) for r in rows["item_template"]}

    def table(name):
        t = defaultdict(list)
        for r in rows[name]:
            t[int(r[0])].append((int(r[1]), float(r[2]), int(r[3]), int(r[4])))
        return t

    clt, rlt = table("creature_loot_template"), table("reference_loot_template")
    ref_users = defaultdict(set)
    for entry, items in clt.items():
        for item, ch, grp, mref in items:
            if mref < 0: ref_users[-mref].add(entry)

    def expand(items, scale, depth=0):
        """[(item, chance%)] for a loot list; groups share what's left of 100% equally."""
        out = []
        groups = defaultdict(list)
        for row in items: groups[row[2]].append(row)
        for grp, rs in groups.items():
            explicit = sum(r[1] for r in rs if r[1] > 0)
            zero = [r for r in rs if r[1] == 0]
            share = (max(0.0, 100 - explicit) / len(zero)) if (grp and zero) else 0
            for item, ch, _, mref in rs:
                c = (ch if ch > 0 else share) * scale / 100.0
                if mref < 0:
                    ref = -mref
                    if depth < 2 and len(ref_users[ref]) <= SHARED_REF:
                        out += expand(rlt.get(ref, []), c, depth + 1)
                    continue
                out.append((item, c))
        return out

    lines = ["-- Generated by tools/gen_loot.py from the CMaNGOS Classic database (GPLv3,",
             "-- https://github.com/cmangos/classic-db): what each dungeon boss drops, item IDs and drop",
             "-- chances (%) only. Names, icons and stats come from the game. Do not edit by hand.",
             "local _, ns = ...",
             "ns.bossLoot = {"]
    n_boss = n_items = 0
    for npc in boss_npcs:
        lid = loot_id.get(npc) or npc
        got = {}
        for item, ch in expand(clt.get(lid, []), 100.0):
            q, cls = item_info.get(item, (0, 0))
            if cls == 12: continue                 # quest items: listed from QuestieDB
            if q < 2 and cls != 9: continue        # uncommon or better, plus recipes
            got[item] = got.get(item, 0) + ch
        items = sorted(((i, c) for i, c in got.items() if c >= MIN_CHANCE), key=lambda x: -x[1])
        if not items: continue
        n_boss += 1; n_items += len(items)
        lines.append(f"  [{npc}]={{" + ",".join(f"{{{i},{round(c, 1)}}}" for i, c in items) + "},")
    # Forever's new dungeons: drops read from Wowhead's WoW Forever NPC pages (tools/forever_loot.json)
    fv_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "forever_loot.json")
    fv = json.load(open(fv_path, encoding="utf-8"))["npc"] if os.path.isfile(fv_path) else {}
    wh = []
    for npc, items in sorted(fv.items(), key=lambda kv: int(kv[0])):
        if int(npc) not in boss_npcs: continue
        wh.append(int(npc)); n_boss += 1; n_items += len(items)
        lines.append(f"  [{npc}]={{" + ",".join(f"{{{i},{c}}}" for i, c, _ in items) + "},")
    lines.append("}")
    lines.append("-- Bosses whose drops come from Wowhead WoW Forever (the rest: the CMaNGOS Classic database)")
    lines.append("ns.bossLootForever = {" + ",".join(f"[{n}]=true" for n in wh) + "}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{n_boss} of {len(boss_npcs)} bosses have loot, {n_items} items -> {OUT}")


main()
